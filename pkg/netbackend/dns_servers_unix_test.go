package netbackend

import (
	"slices"
	"testing"
)

func TestParseResolvConf(t *testing.T) {
	text := `# generated by configd
search corp.example
domain corp.example
nameserver 192.0.2.53
NameServer 2001:db8::53
nameserver fe80::1%en0
; nameserver 192.0.2.99
nameserver 0.0.0.0
nameserver not-an-address
nameserver
options ndots:2
   nameserver   198.51.100.1   
`
	got := parseResolvConf(text)
	want := []string{"192.0.2.53:53", "[2001:db8::53]:53", "[fe80::1%en0]:53", "198.51.100.1:53"}
	if !slices.Equal(got, want) {
		t.Fatalf("parseResolvConf = %v, want %v", got, want)
	}
}

func TestParseResolvConfWithoutNameserversReturnsNoServers(t *testing.T) {
	// The relay must not invent a public resolver when the host has none.
	for _, text := range []string{"", "# only a comment\n", "search example.org\noptions timeout:2\n", "nameserver 0.0.0.0\n"} {
		if got := parseResolvConf(text); len(got) != 0 {
			t.Fatalf("parseResolvConf(%q) = %v, want no servers", text, got)
		}
	}
}
